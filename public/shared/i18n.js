// Taal van de klantpagina's (Nederlands of Engels). Teksten in de code zijn Nederlands en dienen als
// sleutel; tr() geeft in het Engels de vertaling. De teamomgeving blijft altijd Nederlands.
// Inhoud (titels, reacties, briefing, namen) wordt nooit vertaald.
let lang = 'nl';

export function setLang(value) {
  lang = value === 'en' ? 'en' : 'nl';
  if (typeof document !== 'undefined') document.documentElement.lang = lang;
}
export const getLang = () => lang;
/** Locale voor datums: Nederlands, of Brits Engels (dag-maand-jaar, 24-uursklok). */
export const locale = () => (lang === 'en' ? 'en-GB' : 'nl-NL');

/** Vertaal een Nederlandse tekst; {naam} wordt vervangen door vars.naam. */
export function tr(text, vars) {
  let out = lang === 'en' && Object.prototype.hasOwnProperty.call(EN, text) ? EN[text] : text;
  if (vars) out = String(out).replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined && vars[k] !== null ? String(vars[k]) : m));
  return out;
}

